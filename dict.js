  const SYLLABLE_KEYS = Object.keys(SYLLABLE_KATA).sort((a, b) => b.length - a.length);

  function splitPinyinWord(cleanWord) {
    const result = [];
    let i = 0;
    while (i < cleanWord.length) {
      if (cleanWord[i] === "'" || cleanWord[i] === "-") {
        i++;
        continue;
      }
      if (cleanWord[i] === "r" && i === cleanWord.length - 1 && result.length > 0) {
        result.push("er_suffix");
        i++;
        continue;
      }
      let matched = null;
      for (const key of SYLLABLE_KEYS) {
        if (cleanWord.startsWith(key, i)) {
          matched = key;
          break;
        }
      }
      if (matched) {
        result.push(matched);
        i += matched.length;
      } else {
        result.push(cleanWord[i]);
        i++;
      }
    }
    return result;
  }

  function pinyinToKatakana(pinyinText) {
    if (!pinyinText || !pinyinText.trim()) return "";
    const normalized = stripTones(pinyinText.trim());
    const tokens = normalized.split(/\s+/);
    const convertedTokens = tokens.map((token) => {
      const syllables = splitPinyinWord(token);
      return syllables
        .map((syl) => {
          if (syl === "er_suffix") return "ル";
          return SYLLABLE_KATA[syl] || syl;
        })
        .join("");
    });
    return convertedTokens.join(" ");
  }

  function extractWordsFromSentences(sentences) {
    const seen = new Set();
    const results = [];
    const isCjk = (ch) => /[\u4e00-\u9fff]/.test(ch);

    for (const sentence of sentences) {
      let i = 0;
      while (i < sentence.length) {
        if (!isCjk(sentence[i])) {
          i++;
          continue;
        }

        let matchedWord = null;
        const maxTry = Math.min(MAX_WORD_LEN, sentence.length - i);
        for (let len = maxTry; len >= 1; len--) {
          const sub = sentence.slice(i, i + len);
          if (WORD_MAP.has(sub)) {
            matchedWord = sub;
            break;
          }
        }

        const token = matchedWord || sentence[i];
        if (!seen.has(token)) {
          seen.add(token);
          const entry = WORD_MAP.get(token);
          if (entry) {
            results.push({ ...entry });
          } else {
            results.push({
              word: token,
              pinyin: "",
              katakana: "",
              ja: "",
              pos: "その他"
            });
          }
        }
        i += token.length;
      }
    }
    return results;
  }

  function lookupWord(word) {
    return WORD_MAP.get(word.trim()) || null;
  }

  function normalizePos(rawPos) {
    const s = (rawPos || "").trim().toLowerCase();
    if (!s) return "その他";
    if (s.includes("動") || s === "v" || s === "verb") return "動詞";
    if (s.includes("形") || s === "adj" || s === "adjective") return "形容詞";
    if (s.includes("名") || s === "n" || s === "noun") return "名詞";
    return "その他";
  }

  return {
    pinyinToKatakana,
    extractWordsFromSentences,
    lookupWord,
    normalizePos
  };
